// One-off dev script: for every DB row that's a regional/form variant (not
// a species' canonical/base row), finds that specific form's PokeAPI
// numeric pokemon id — so the static-artwork sprite fallback can show the
// correct form's art instead of always falling back to the base species'
// (keyed by national dex number, which is form-unaware). Writes a static
// lookup, does not touch Supabase. Run with:
//   node scripts/resolve-pokeapi-ids.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.join(__dirname, "..", ".env.local");
const env = Object.fromEntries(
  fs
    .readFileSync(envPath, "utf-8")
    .split("\n")
    .filter((l) => l.includes("="))
    .map((l) => {
      const idx = l.indexOf("=");
      return [l.slice(0, idx).trim(), l.slice(idx + 1).trim()];
    })
);

const SUPABASE_URL = env.SUPABASE_URL;
const SUPABASE_ANON_KEY = env.SUPABASE_ANON_KEY;
const PAGE_SIZE = 1000;

const VARIANT_PREFIXES = ["Mega", "Primal", "Alolan", "Galarian", "Hisuian", "Paldean"];
function isFormVariant(name) {
  const trimmed = name.trim();
  if (VARIANT_PREFIXES.some((p) => new RegExp(`^${p}\\s+`, "i").test(trimmed))) return true;
  if (/\(.+\)/.test(trimmed)) return true;
  return false;
}

// Distinguishing tokens we expect a matching PokeAPI variety name to contain.
const REGION_TOKENS = { Alolan: "alola", Galarian: "galar", Hisuian: "hisui", Paldean: "paldea" };

function expectedTokens(name) {
  const tokens = [];
  for (const [prefix, token] of Object.entries(REGION_TOKENS)) {
    if (new RegExp(`^${prefix}\\s+`, "i").test(name)) tokens.push(token);
  }
  const parenMatch = name.match(/\(([^)]+)\)/);
  if (parenMatch) {
    for (const word of parenMatch[1].toLowerCase().split(/\s+/)) tokens.push(word);
  }
  return tokens;
}

async function fetchAllRows() {
  const rows = [];
  let start = 0;
  for (;;) {
    const res = await fetch(
      `${SUPABASE_URL}/rest/v1/pokemon?select=id,pokedex_number,name&order=id.asc&offset=${start}&limit=${PAGE_SIZE}`,
      { headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` } }
    );
    const page = await res.json();
    rows.push(...page);
    if (page.length < PAGE_SIZE) break;
    start += PAGE_SIZE;
  }
  return rows;
}

async function poolMap(items, concurrency, fn) {
  const results = new Array(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      try {
        results[i] = await fn(items[i], i);
      } catch (e) {
        results[i] = { error: String(e) };
      }
    }
  }
  await Promise.all(Array.from({ length: concurrency }, worker));
  return results;
}

async function fetchJson(url) {
  const res = await fetch(url);
  if (!res.ok) return null;
  return res.json();
}

const rows = await fetchAllRows();
const variantRows = rows.filter((r) => isFormVariant(r.name));
console.log(`${variantRows.length} rows look like form variants. Resolving PokeAPI ids...`);

const speciesNeeded = [...new Set(variantRows.map((r) => r.pokedex_number))];
const speciesData = await poolMap(speciesNeeded, 10, async (dexNum) => {
  const species = await fetchJson(`https://pokeapi.co/api/v2/pokemon-species/${dexNum}`);
  return { dexNum, varieties: species?.varieties ?? [] };
});
const speciesByDex = new Map(speciesData.map((s) => [s.dexNum, s.varieties]));

const overrides = {};
const unresolved = [];

for (const row of variantRows) {
  const varieties = speciesByDex.get(row.pokedex_number) ?? [];
  const tokens = expectedTokens(row.name);
  if (!tokens.length || !varieties.length) {
    unresolved.push(row);
    continue;
  }

  let best = null;
  let bestScore = 0;
  for (const v of varieties) {
    const vName = v.pokemon.name.toLowerCase();
    const score = tokens.filter((t) => vName.includes(t)).length;
    if (score > bestScore) {
      bestScore = score;
      best = v;
    }
  }

  if (best && bestScore === tokens.length) {
    const idMatch = best.pokemon.url.match(/\/pokemon\/(\d+)\//);
    if (idMatch) {
      overrides[row.id] = Number(idMatch[1]);
      continue;
    }
  }
  unresolved.push(row);
}

console.log(`Resolved: ${Object.keys(overrides).length} / ${variantRows.length}`);
if (unresolved.length) {
  console.log("Unresolved (will keep using national-dex-number artwork fallback):");
  for (const r of unresolved) console.log(`  id=${r.id} "${r.name}" (#${r.pokedex_number})`);
}

const outPath = path.join(__dirname, "..", "src", "lib", "pokeapi-id-overrides.ts");
const body = `// Generated by scripts/resolve-pokeapi-ids.mjs.
// Maps a DB row id (regional/form variants only) to its own PokeAPI numeric
// pokemon id, so the static-artwork sprite fallback shows the correct
// form's art instead of the base species' (official-artwork is keyed by
// PokeAPI id, not national dex number, and form variants get their own id).
export const POKEAPI_ID_OVERRIDES: Record<number, number> = ${JSON.stringify(overrides, null, 2)};
`;
fs.writeFileSync(outPath, body);
console.log(`Wrote ${Object.keys(overrides).length} overrides to ${outPath}`);

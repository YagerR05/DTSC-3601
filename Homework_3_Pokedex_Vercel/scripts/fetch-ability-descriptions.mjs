// One-off dev script: builds a static ability-name -> description lookup
// from PokeAPI, covering every ability actually used in the `pokemon` table.
// Not part of the Next.js build. Run with:
//   node scripts/fetch-ability-descriptions.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const envPath = path.join(__dirname, "..", ".env.local");
const env = Object.fromEntries(
  fs
    .readFileSync(envPath, "utf-8")
    .split("\n")
    .filter((l) => l.includes("="))
    .map((l) => {
      const idx = l.indexOf("=");
      return [l.slice(0, idx).trim(), l.slice(idx + 1).trim()];
    })
);

const SUPABASE_URL = env.SUPABASE_URL;
const SUPABASE_ANON_KEY = env.SUPABASE_ANON_KEY;
const PAGE_SIZE = 1000;

function parseAbilities(raw) {
  const match = raw.match(/'([^']*)'|"([^"]*)"/g);
  if (!match) return [];
  return match.map((s) => s.slice(1, -1));
}

// The DB's abilities column occasionally concatenates words that PokeAPI's
// slug hyphenates (a dataset quirk, not a general pattern) — override those.
const SLUG_OVERRIDES = {
  Compoundeyes: "compound-eyes",
  Lightningrod: "lightning-rod",
};

function toSlug(name) {
  return SLUG_OVERRIDES[name] ?? name.trim().toLowerCase().replace(/\s+/g, "-");
}

async function fetchAllAbilityNames() {
  const names = new Set();
  let start = 0;
  for (;;) {
    const res = await fetch(
      `${SUPABASE_URL}/rest/v1/pokemon?select=abilities&order=id.asc&offset=${start}&limit=${PAGE_SIZE}`,
      { headers: { apikey: SUPABASE_ANON_KEY, Authorization: `Bearer ${SUPABASE_ANON_KEY}` } }
    );
    const page = await res.json();
    for (const row of page) {
      for (const a of parseAbilities(row.abilities)) names.add(a);
    }
    if (page.length < PAGE_SIZE) break;
    start += PAGE_SIZE;
  }
  return [...names].sort();
}

async function poolMap(items, concurrency, fn) {
  const results = new Array(items.length);
  let next = 0;
  async function worker() {
    while (next < items.length) {
      const i = next++;
      results[i] = await fn(items[i], i);
    }
  }
  await Promise.all(Array.from({ length: concurrency }, worker));
  return results;
}

async function fetchDescription(name) {
  const slug = toSlug(name);
  try {
    const res = await fetch(`https://pokeapi.co/api/v2/ability/${slug}`);
    if (!res.ok) return { name, description: null, miss: true };
    const data = await res.json();
    const entries = data.effect_entries.filter((e) => e.language.name === "en");
    const text = entries[0]?.short_effect ?? entries[0]?.effect ?? null;
    return { name, description: text ? text.replace(/\s+/g, " ").trim() : null, miss: !text };
  } catch {
    return { name, description: null, miss: true };
  }
}

const names = await fetchAllAbilityNames();
console.log(`Found ${names.length} unique abilities. Fetching descriptions...`);

const results = await poolMap(names, 8, fetchDescription);
const misses = results.filter((r) => r.miss);
console.log(`OK: ${results.length - misses.length} / ${results.length}`);
if (misses.length) {
  console.log("Misses (no description found, will need a manual override):");
  for (const m of misses) console.log(`  "${m.name}" -> slug "${toSlug(m.name)}"`);
}

const lookup = Object.fromEntries(
  results.filter((r) => r.description).map((r) => [r.name, r.description])
);

const outPath = path.join(__dirname, "..", "src", "lib", "ability-descriptions.ts");
const body = `// Generated by scripts/fetch-ability-descriptions.mjs from PokeAPI effect text.
// Keyed by the ability name exactly as it appears in the DB's \`abilities\` column.
export const ABILITY_DESCRIPTIONS: Record<string, string> = ${JSON.stringify(lookup, null, 2)};
`;
fs.writeFileSync(outPath, body);
console.log(`Wrote ${Object.keys(lookup).length} descriptions to ${outPath}`);
